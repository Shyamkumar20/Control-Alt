const CATEGORY_BY_SLUG = new Map(CATEGORIES.map((category) => [category.slug, category]));
const CATEGORY_BY_TOPIC = new Map<string, CategoryDefinition>();

for (const category of CATEGORIES) {
  for (const topic of category.topics) {
    CATEGORY_BY_TOPIC.set(topic, category);
  }
}

export function getCategoryBySlug(slug: string): CategoryDefinition | undefined {
  return CATEGORY_BY_SLUG.get(slug as CategorySlug);
}

export function getCategoryForTopic(topic: string): CategoryDefinition | undefined {
  return CATEGORY_BY_TOPIC.get(topic.toLowerCase());
}

export function getCategorySlugsForTopics(topics: string[]): CategorySlug[] {
  const slugs = new Set<CategorySlug>();
  for (const topic of topics) {
    const category = getCategoryForTopic(topic);
    if (category) slugs.add(category.slug);
  }
  return Array.from(slugs);
}
